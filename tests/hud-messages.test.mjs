import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../hud-messages.inc.js',import.meta.url),'utf8');
test('long phone notifications stay above the player and preserve the search countdown',()=>{
 const boxes=[],text=[];
 const ctx={save(){},restore(){},beginPath(){},fill(){},stroke(){},roundRect(...r){boxes.push(r)},fillText(t){text.push(t)},measureText:t=>({width:t.length*6})};
 const c=vm.createContext({ctx,RELEASE_OFFICERS:[],peds:[],cops:[],simT:10,MS:null,FREE:()=>true,compactTouch:()=>true,deviceInsets:()=>({top:0,left:0,right:0}),mobileObjectiveText:()=>'',drawSpeechBubble(){},drawPursuitHUD(){}});
 vm.runInContext(source,c);
 const h={msgT:5,msg:'A very long dispatch notification. '.repeat(30)};
 c.drawPursuitHUD({x:0,w:568,h:320},h,.85);
 assert(boxes[0][1]+boxes[0][3]<140,'notification must leave the central driving area clear');
 assert(text.some(t=>t.endsWith('…')));
 boxes.length=0;text.length=0;h.pursuit={phase:'search',remaining:43.2};h.wanted=2;
 c.drawPursuitHUD({x:0,w:568,h:320},h,.85);
 assert(boxes[0][1]+boxes[0][3]<140);assert(text.some(t=>t.includes('STAY HIDDEN · 44s')));
 const lines=c.hudMessageLines('Short instruction.',200,t=>t.length*6,2);
 assert.equal(lines.join(' '),'Short instruction.');
});
